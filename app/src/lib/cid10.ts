export function buscarCID(t: string): [string, string][] {
  const q = t
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
  if (!q) return [];
  return CID10.filter(([c, d]) => {
    const dd = d.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
    return c.toLowerCase().startsWith(q) || c.toLowerCase().replace(".", "").startsWith(q) || dd.includes(q);
  }).slice(0, 12);
}
