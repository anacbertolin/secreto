-- =====================================================================
-- 0183 — Carga do Micrologos: modo "atualizar" (sessão "Dados para migração", 26/11/2026)
-- Alguns registros já existem no sistema e precisam ser COMPLETADOS pela carga (não duplicados):
--   - convênios Unimed provisórios (migração 0176): ganham planos, TISS e preços;
--   - pacientes que a equipe cadastrou antes da troca: assumem o nº do Micrologos e o que faltar no cadastro.
-- p_atualizar = true: se a chave primária já existe, atualiza as colunas enviadas (em vez de ignorar).
-- O nº do prontuário precisa poder ser trocado nesses casos: a coluna passa a "generated by default" (o sistema
-- continua gerando o nº sozinho; só a carga informa um nº).
-- =====================================================================
alter table public.pacientes alter column numero_prontuario set generated by default;

drop function if exists public.carga_micrologos(text, jsonb, boolean);
create or replace function public.carga_micrologos(p_tabela text, p_linhas jsonb, p_simular boolean default false,
                                                   p_atualizar boolean default false)
returns integer language plpgsql volatile security definer set search_path = '' as $$
declare
  v_schema text := split_part(p_tabela, '.', 1);
  v_nome   text := split_part(p_tabela, '.', 2);
  v_cols   text;
  v_pk     text;
  v_set    text;
  v_acao   text := 'do nothing';
  v_n      integer := 0;
begin
  if v_schema not in ('public', 'legacy_micrologos') or v_nome = '' then
    raise exception 'Tabela inválida: %', p_tabela;
  end if;
  if jsonb_typeof(p_linhas) <> 'array' or jsonb_array_length(p_linhas) = 0 then
    return 0;
  end if;
  select string_agg(quote_ident(c.column_name), ', ' order by c.ordinal_position) into v_cols
  from information_schema.columns c
  where c.table_schema = v_schema and c.table_name = v_nome and c.is_generated = 'NEVER'
    and (p_linhas -> 0) ? c.column_name;
  if v_cols is null then
    raise exception 'Tabela % não encontrada ou sem colunas em comum', p_tabela;
  end if;
  if p_atualizar then
    select string_agg(quote_ident(a.attname), ', ') into v_pk
    from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
    where i.indrelid = format('%I.%I', v_schema, v_nome)::regclass and i.indisprimary;
    select string_agg(format('%1$I = excluded.%1$I', c.column_name), ', ') into v_set
    from information_schema.columns c
    where c.table_schema = v_schema and c.table_name = v_nome and c.is_generated = 'NEVER'
      and (p_linhas -> 0) ? c.column_name
      and c.column_name not in (select a.attname from pg_index i join pg_attribute a on a.attrelid = i.indrelid
                                and a.attnum = any (i.indkey)
                                where i.indrelid = format('%I.%I', v_schema, v_nome)::regclass and i.indisprimary);
    if v_pk is null or v_set is null then
      raise exception 'Tabela % sem chave primária para atualizar', p_tabela;
    end if;
    v_acao := format('(%s) do update set %s', v_pk, v_set);
  end if;
  perform set_config('app.migracao', 'on', true);
  begin
    execute format(
      'insert into %I.%I (%s) overriding system value select %s from jsonb_populate_recordset(null::%I.%I, $1) on conflict %s',
      v_schema, v_nome, v_cols, v_cols, v_schema, v_nome, v_acao) using p_linhas;
    get diagnostics v_n = row_count;
    if p_simular then
      raise exception using errcode = 'P0001', message = 'SIMULADO:' || v_n;
    end if;
  exception when sqlstate 'P0001' then
    if sqlerrm like 'SIMULADO:%' then
      return split_part(sqlerrm, ':', 2)::integer;
    end if;
    raise;
  end;
  return v_n;
end $$;
revoke execute on function public.carga_micrologos(text, jsonb, boolean, boolean) from public, anon, authenticated;
grant execute on function public.carga_micrologos(text, jsonb, boolean, boolean) to service_role;
comment on function public.carga_micrologos(text, jsonb, boolean, boolean) is
  'Carga do Micrologos (só a chave secreta). Insere (ou atualiza, com p_atualizar) com app.migracao ligado; simular = grava e desfaz.';
